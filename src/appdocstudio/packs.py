def _module_table(p: ProjectInfo) -> str:
    if not p.modules:
        return "_No parseable source modules (Python / TypeScript / JavaScript) were found._"
    rows = ["| Module | Language | Lines | Functions | Classes |",
            "|---|---|---:|---:|---:|"]
    for m in p.modules:
        rows.append(f"| `{m.path}` | {m.language} | {m.lines} | "
                    f"{len(m.functions) + sum(len(c.methods) for c in m.classes)} | {len(m.classes)} |")
    return "\n".join(rows)


def _api_reference(p: ProjectInfo) -> str:
    if not p.modules:
        return "_No API surface was extracted._"
    out: list[str] = []
    for m in p.modules:
        if not (m.functions or m.classes):
            continue
        out.append(f"#### `{m.path}`")
        out.append("")
        if m.summary:
            out.append(m.summary)
            out.append("")
        for fn in m.functions:
            out.append(f"- `{fn.signature()}` — {fn.summary or '_(no doc comment)_'}")
        for cls in m.classes:
            bases = f" ({', '.join(cls.bases)})" if cls.bases else ""
            out.append(f"- **{cls.kind} `{cls.name}`**{bases} — {cls.summary or '_(no doc comment)_'}")
            for meth in cls.methods:
                out.append(f"  - `{meth.signature()}` — {meth.summary or '_(no doc comment)_'}")
            for prop in cls.properties:
                out.append(f"  - property `{prop.signature()}`")
        for alias in m.type_aliases:
            out.append(f"- type `{alias}`")
        out.append("")
    return "\n".join(out).rstrip()


def _licence_table(p: ProjectInfo) -> str:
    if not p.licences:
        return "_No licence identifiers were detected. Add a LICENSE file and SPDX identifiers so this inventory can be generated._"
    rows = ["| SPDX identifier | Source |", "|---|---|"]
    for lic in p.licences:
        rows.append(f"| `{lic.spdx}` | {lic.source} |")
    return "\n".join(rows)


def _openapi_block(p: ProjectInfo) -> str:
    if not p.openapi:
        return "_No OpenAPI description was found in this project. If the project exposes an HTTP API, add an OpenAPI 3.1 description (`openapi.json`) and this section will document it._"
    lines = [f"OpenAPI description found at `{p.openapi['path']}`"
             + (f" — **{p.openapi.get('title')}**" if p.openapi.get("title") else "")
             + (f" (version {p.openapi.get('version')})" if p.openapi.get("version") else "") + "."]
    paths = p.openapi.get("paths") or []
    if paths:
        lines.append("")
        lines.append("Endpoints:")
        lines.append("")
        for path in paths:
            lines.append(f"- `{path}`")
    return "\n".join(lines)


def _scripts_block(p: ProjectInfo, empty: str) -> str:
    if not p.scripts:
        return empty
    rows = ["| Script | Command |", "|---|---|"]
    for name, cmd in sorted(p.scripts.items()):
        rows.append(f"| `{name}` | `{cmd}` |")
    return "\n".join(rows)


