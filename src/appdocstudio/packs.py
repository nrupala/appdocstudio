def _users(p: ProjectInfo) -> Pack:
    pack = Pack(role="users", title=ROLE_TITLES["users"])
    features = [m.summary for m in p.modules if m.summary][:8]
    feature_list = "\n".join(f"- {s}" for s in features) if features else \
        f"- {p.description or 'See the project README for the feature overview.'}"
    pack.sections = [
        Section("Tutorial", "Getting started",
                f"1. Obtain {p.name} from its project page or your administrator.\n"
                f"2. Follow the project's README quick start.\n"
                f"3. Work through one complete task end to end before exploring advanced options.\n\n"
                f"This guide was generated from the codebase itself, so the feature descriptions below reflect what the code says it does."),
        Section("How-to", "Common tasks",
                "Pick the module that matches your task from the reference table below, "
                "then follow that module's own documentation. If a task is missing here, "
                "it is missing from the code's documentation too — raise it with the maintainers."),
        Section("Reference", "What the product contains", _module_table(p)),
        Section("Explanation", "What this product is",
                (p.description or f"{p.name} is documented here from its own source code. "
                                    "Each module below states its purpose in its own words "
                                    "(its module docstring or header comment):") + "\n\n" + feature_list),
    ]
    return pack


def _developers(p: ProjectInfo) -> Pack:
    pack = Pack(role="developers", title=ROLE_TITLES["developers"])
    imports = sorted({imp for m in p.modules for imp in m.imports})
    deps = "\n".join(f"- `{d}`" for d in p.dependencies) if p.dependencies else "_No declared dependencies were detected._"
    pack.sections = [
        Section("Tutorial", "Set up and make your first change",
                "1. Clone the repository.\n"
                "2. Install the dependencies listed in the Explanation section.\n"
                "3. Run the project's own test suite (if present) to establish a green baseline.\n"
                "4. Pick one function from the API reference, read its doc comment, and trace one call."),
        Section("How-to", "Extend the codebase",
                "Add new behaviour as a new function or class in the module that owns the "
                "closest existing behaviour, document it at the point of definition "
                "(TSDoc/JSDoc for TypeScript/JavaScript, Google-style docstrings for Python), "
                "and regenerate this guide — doc comments are the source of this reference."),
        Section("Reference", "API reference", _api_reference(p)),
        Section("Reference", "HTTP API (OpenAPI)", _openapi_block(p)),
        Section("Explanation", "Architecture and dependencies",
                f"The codebase contains {len(p.modules)} parsed modules "
                f"({sum(len(m.functions) for m in p.modules)} top-level functions, "
                f"{sum(len(m.classes) for m in p.modules)} classes/interfaces).\n\n"
                f"Declared dependencies:\n\n{deps}\n\n"
                + (f"External modules imported: {', '.join(f'`{i}`' for i in imports[:40])}." if imports else "")),
    ]
    return pack


def _maintainers(p: ProjectInfo) -> Pack:
    pack = Pack(role="maintainers", title=ROLE_TITLES["maintainers"])
    undocumented = [(m.path, f.name) for m in p.modules for f in
                    (m.functions + [meth for c in m.classes for meth in c.methods]) if not f.summary]
    noun = "item" if len(undocumented) == 1 else "items"
    drift = (f"{len(undocumented)} documented-surface {noun} have no doc comment. "
             "First five: " + ", ".join(f"`{path}::{name}`" for path, name in undocumented[:5]) + "."
             if undocumented else "Every function and method in the documented surface carries a doc comment.")
    pack.sections = [
        Section("Tutorial", "Your first maintenance session",
                "1. Scan the project and regenerate these packs; diff them against the committed copies.\n"
                "2. Any diff is documentation drift — resolve it in the same change as the code.\n"
                "3. Run the test suite before and after your change."),
        Section("How-to", "Cut a release",
                "1. Ensure the working tree is clean and tests pass.\n"
                "2. Regenerate documentation and review the diff as part of the release notes.\n"
                "3. Update the changelog and tag the release per the project's CONTRIBUTING rules.\n"
                "4. Record the release-gate verdict in the release notes."),
        Section("Reference", "Licence inventory (SPDX)", _licence_table(p)),
        Section("Reference", "Module inventory", _module_table(p)),
        Section("Explanation", "Documentation health", drift),
    ]
    return pack


def _regulators(p: ProjectInfo) -> Pack:
    pack = Pack(role="regulators", title=ROLE_TITLES["regulators"])
    inventory = ["| File | SHA-256 (first 16) | Lines |", "|---|---|---:|"]
    for m in p.modules:
        inventory.append(f"| `{m.path}` | `{(m.sha256 or '')[:16]}` | {m.lines} |")
    pack.sections = [
        Section("Tutorial", "How to use this pack",
                "This pack assembles documentation that supports an audit or compliance "
                "review of this codebase: what the code is, what licences it carries, and a "
                "hash inventory of the scanned source files so a reviewer can verify that "
                "the code reviewed is the code described.\n\n"
                "**Scope statement.** AppDocStudio assembles documentation that supports "
                "evidence production for frameworks such as SOC 2 and ISO/IEC 27001. It does "
                "**not** certify compliance with any standard, and nothing in this pack is a "
                "certification, an audit opinion, or a guarantee."),
        Section("How-to", "Verify this pack against the code",
                "1. Re-run the scan on the exact commit under review.\n"
                "2. Compare the SHA-256 prefixes in the inventory below with the regenerated output.\n"
                "3. Any mismatch means the code changed after this pack was generated."),
        Section("Reference", "Licence and component inventory (SPDX)",
                _licence_table(p) + "\n\nA machine-readable component inventory (CycloneDX) "
                "is generated alongside this pack as `sbom.cdx.json` when docs are generated "
                "with the CLI or MCP server."),
        Section("Reference", "Source file inventory with hashes", "\n".join(inventory)),
        Section("Explanation", "What the code claims to do", _api_reference(p)),
    ]
    return pack


def _admins(p: ProjectInfo) -> Pack:
    pack = Pack(role="admins", title=ROLE_TITLES["admins"])
    configs = "\n".join(f"- `{c}`" for c in p.config_files) if p.config_files else "_No configuration files were detected._"
    pack.sections = [
        Section("Tutorial", "Install and configure",
                "1. Deploy from the project's release or repository.\n"
                "2. Review each configuration file listed in the Reference section before first run.\n"
                "3. Keep secrets out of the repository — use the project's `.env.example` pattern where present."),
        Section("How-to", "Backup and restore",
                "Back up the configuration files listed below together with any data the "
                "deployment creates. Restore by redeploying the same version and reapplying "
                "the backed-up configuration; verify with the project's health check or test suite."),
        Section("Reference", "Configuration files", configs),
        Section("Reference", "Runtime scripts", _scripts_block(p, "_No package scripts were detected._")),
        Section("Explanation", "Licence obligations for operators", _licence_table(p)),
    ]
    return pack


def _ops(p: ProjectInfo) -> Pack:
    pack = Pack(role="ops", title=ROLE_TITLES["ops"])
    ci = "\n".join(f"- `{w}`" for w in p.ci_workflows) if p.ci_workflows else "_No CI workflows were detected._"
    pack.sections = [
        Section("Tutorial", "Bring the service up",
                "1. Deploy the current released version.\n"
                "2. Apply the configuration reviewed in the Administrator Guide.\n"
                "3. Run the project's checks and confirm the primary flow works end to end."),
        Section("How-to", "Respond to an incident",
                "1. Identify the deployed version and its documentation pack.\n"
                "2. Check the CI/deployment status (workflows below).\n"
                "3. Roll back to the last known-good release if the primary flow is broken; "
                "diagnose after service is restored."),
        Section("Reference", "CI / deployment workflows", ci),
        Section("Reference", "Operational scripts", _scripts_block(p, "_No package scripts were detected._")),
        Section("Explanation", "System shape",
                f"{p.name} comprises {p.total_files} files and {len(p.modules)} parsed source modules. "
                "The module inventory in the Maintainer Guide is the authoritative map of what runs where."),
    ]
    return pack


_BUILDERS = {"users": _users, "developers": _developers, "maintainers": _maintainers,
             "regulators": _regulators, "admins": _admins, "ops": _ops}


def build_pack(project: ProjectInfo, role: str) -> Pack:
    if role not in _BUILDERS:
        raise ValueError(f"Unknown role '{role}'. Valid roles: {', '.join(ROLES)}")
    return _BUILDERS[role](project)


def build_all_packs(project: ProjectInfo) -> list[Pack]:
    return [build_pack(project, role) for role in ROLES]


def cyclonedx_bom(project: ProjectInfo) -> dict:
    """A CycloneDX 1.5 component inventory derived from the scan."""
    components = []
    for dep in project.dependencies:
        # Per-dependency licence data is not collected by the scan; the
        # project's own licences live in metadata.component below.
        components.append({"type": "library", "name": dep})
    return {
        "bomFormat": "CycloneDX",
        "specVersion": "1.5",
        "version": 1,
        "metadata": {
            "component": {"type": "application", "name": project.name,
                          "licenses": [{"license": {"id": lic.spdx}} for lic in project.licences]},
            "tools": [{"name": "AppDocStudio", "vendor": "2351485 ALBERTA INC."}],
        },
        "components": components,
    }


def bom_json(project: ProjectInfo) -> str:
    return json.dumps(cyclonedx_bom(project), indent=2) + "\n"
