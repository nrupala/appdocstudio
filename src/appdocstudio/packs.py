"""Role packs — one scan, six audience-tailored documentation sets.

Every pack is structured on the Diátaxis framework (tutorial, how-to,
reference, explanation) and rendered to CommonMark Markdown or to
WCAG-conscious HTML (see html_render.py). The standards these outputs are
designed to meet are listed in docs/STANDARDS.md; they are design targets,
not certifications.

Copyright 2026 2351485 ALBERTA INC. — SPDX-License-Identifier: Apache-2.0
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field

from .model import ProjectInfo

ROLES = ("users", "developers", "maintainers", "regulators", "admins", "ops")
ROLE_TITLES = {
    "users": "User Guide",
    "developers": "Developer Guide",
    "maintainers": "Maintainer Guide",
    "regulators": "Regulator & Compliance Evidence Pack",
    "admins": "Administrator Guide",
    "ops": "Operations Runbook",
}
QUADRANTS = ("Tutorial", "How-to", "Reference", "Explanation")


@dataclass
class Section:
    quadrant: str
    heading: str
    body: str  # Markdown


@dataclass
class Pack:
    role: str
    title: str
    sections: list[Section] = field(default_factory=list)

    def to_markdown(self, project: ProjectInfo, doc_format: str = "diataxis") -> str:
        from .formats import _front_body, get_format
        profile = get_format(doc_format)
        lines = [f"# {project.name} — {profile.heading(self.title)}", ""]
        lines.append(f"Generated by AppDocStudio from a scan of `{project.name}` "
                     f"({project.total_files} files, {project.total_lines} lines of source). "
                     "Structure follows the Diátaxis framework (tutorial / how-to / reference / explanation).")
        if profile.id != "diataxis":
            lines.append("")
            lines.append(f"Rendered in the **{profile.name}**: {profile.authority}.")
        if profile.conventions_note:
            lines.append("")
            lines.append(profile.conventions_note)
        lines.append("")
        for label in profile.front:
            lines.append(f"## {profile.heading(label)}")
            lines.append("")
            lines.append(_front_body(label, project, self))
            lines.append("")
        current = None
        clause = 0
        sub = 0
        for section in self.sections:
            if section.quadrant != current:
                current = section.quadrant
                clause += 1
                sub = 0
                heading = profile.heading(profile.quadrant(current))
                if profile.numbered:
                    heading = f"{clause} {heading}"
                lines.append(f"## {heading}")
                lines.append("")
            sub += 1
            heading = profile.heading(section.heading)
            if profile.numbered:
                heading = f"{clause}.{sub} {heading}"
            lines.append(f"### {heading}")
            lines.append("")
            lines.append(section.body.rstrip())
            lines.append("")
        if profile.footer:
            lines.append(profile.footer.format(name=project.name))
            lines.append("")
        return "\n".join(lines).rstrip() + "\n"


