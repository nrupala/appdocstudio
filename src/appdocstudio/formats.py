FORMAT_IDS = tuple(FORMATS)
DEFAULT_FORMAT = "diataxis"


def get_format(format_id: str | None) -> FormatProfile:
    fid = (format_id or DEFAULT_FORMAT).lower()
    if fid not in FORMATS:
        raise ValueError(f"Unknown format '{format_id}'. Valid formats: {', '.join(FORMAT_IDS)}")
    return FORMATS[fid]


# Front-matter bodies, keyed by the labels used in FormatProfile.front.
def _front_body(label: str, project, pack) -> str:
    name = project.name
    if label == "Abstract":
        return (f"This document is the {pack.title.lower()} for {name}, generated from "
                f"the project's source code ({project.total_files} files, "
                f"{project.total_lines} lines). It describes the documented surface "
                "as extracted by AppDocStudio.")
    if label == "Status of This Document":
        return ("This section describes the status of this document at the time of "
                "generation. It is a generated project document, produced by "
                "AppDocStudio from source code, and is expected to be regenerated "
                "whenever the code changes.")
    if label == "Foreword":
        return (f"This document was prepared by automated documentation generation "
                f"(AppDocStudio) from the source code of {name}. It assembles the "
                "project's documented surface — module purposes, interfaces, licences, "
                "and configuration — into the structure defined by the drafting rules "
                "of the format it follows.")
    if label == "European foreword":
        return ("This document has been prepared by automated documentation generation "
                "(AppDocStudio) from the project's source code. It is a project "
                "document; it has not been adopted by any national standards body "
                "and is not a European Standard.")
    if label == "Introduction":
        return (f"This document introduces {name} by audience: what it contains, how "
                "to use it, and the reference material that defines its surface. "
                "Clause numbering and verbal forms follow the drafting rules named "
                "in the conventions note.")
    if label == "About this document":
        return (f"{_GENERATED} It follows the structure used by Apache Software "
                "Foundation project documentation: an overview first, then task "
                "guidance, reference material, and background.")
    if label == "In this article":
        return ("This article covers the generated documentation for "
                f"{name} by audience and task.")
    return _GENERATED
