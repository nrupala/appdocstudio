"""Standards-format packs — the same scan, rendered per house standard.

AppDocStudio's spine is Diátaxis structure over ISO/IEC/IEEE 26514 &
15289-conformant content. On top of that spine, a *format profile* renders
a pack in the structure and style of a documentation standard or house
style:

- ``diataxis``  — the base rendering (no house style applied)
- ``apache``    — Apache Software Foundation project documentation conventions
- ``google``    — Google developer documentation style guide
- ``microsoft`` — Microsoft Writing Style Guide / Microsoft Learn conventions
- ``apple``     — Apple Style Guide conventions
- ``w3c``       — W3C specification conventions (ReSpec-style front matter,
                  RFC 2119 conformance keywords)
- ``iso``       — ISO/IEC Directives, Part 2 drafting structure
- ``ansi``      — ANSI American National Standard structure
- ``en``        — European Standard (EN) structure (CEN/CENELEC)

A profile changes what is mechanically checkable: front matter, section
naming, heading case, clause numbering, callout and footer conventions.
Profiles are **design targets**: a pack rendered in the ISO profile follows
the ISO drafting structure; it is not an ISO standard and claims no
certification — the same honesty rule as docs/STANDARDS.md.

Copyright 2026 2351485 ALBERTA INC. — SPDX-License-Identifier: Apache-2.0
"""

from __future__ import annotations

from dataclasses import dataclass, field

_SMALL_WORDS = {"a", "an", "the", "and", "or", "of", "to", "in", "on", "for", "with"}


def sentence_case(text: str) -> str:
    """Sentence case: first word capitalised, the rest lowered except
    tokens that look like proper nouns / identifiers (contain an uppercase
    letter beyond position 0, digits, or are ALL-CAPS)."""
    words = text.split(" ")
    out = []
    for i, w in enumerate(words):
        if i == 0:
            out.append(w[:1].upper() + w[1:])
        elif any(ch.isupper() for ch in w[1:]) or any(ch.isdigit() for ch in w) or w.isupper():
            out.append(w)
        else:
            out.append(w.lower())
    return " ".join(out)


def title_case(text: str) -> str:
    words = text.split(" ")
    out = []
    for i, w in enumerate(words):
        if i > 0 and w.lower() in _SMALL_WORDS:
            out.append(w.lower())
        else:
            out.append(w[:1].upper() + w[1:])
    return " ".join(out)


@dataclass
class FormatProfile:
    id: str
    name: str
    authority: str          # the standard / style guide the profile follows
    heading_case: str = "asis"          # asis | sentence | title
    numbered: bool = False              # clause numbering (ISO/ANSI/EN style)
    quadrant_names: dict = field(default_factory=dict)   # Diátaxis -> house name
    front: tuple = ()                   # front-matter block templates (see formats)
    footer: str = ""                    # closing block, may use {name}
    conventions_note: str = ""          # verbal-forms / keyword conventions line

    def heading(self, text: str) -> str:
        if self.heading_case == "sentence":
            return sentence_case(text)
        if self.heading_case == "title":
            return title_case(text)
        return text

    def quadrant(self, quadrant: str) -> str:
        return self.quadrant_names.get(quadrant, quadrant)


